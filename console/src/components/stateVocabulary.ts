// --- Time helpers (P0.09 UTC unix millis discipline) -------------------------

/** Formats UTC unix millis as an ISO 8601 UTC string (or '—' when null). */
export function formatUtcMillis(millis: number | null | undefined): string {
  if (millis === null || millis === undefined) return '—';
  return new Date(millis).toISOString();
}

/** A plain human age for a fetched-at instant ("12s ago"). */
export function describeAge(iso: string, nowIso: string = new Date().toISOString()): string {
  const ageMs = Date.parse(nowIso) - Date.parse(iso);
  if (!Number.isFinite(ageMs) || ageMs < 0) return 'unknown age';
  const seconds = Math.floor(ageMs / 1000);
  if (seconds < 60) return `${seconds}s ago`;
  const minutes = Math.floor(seconds / 60);
  if (minutes < 60) return `${minutes}m ago`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours}h ago`;
  return `${Math.floor(hours / 24)}d ago`;
}
