fn hex_bytes(hex: &str) -> Vec<u8> {
    let bytes = hex.as_bytes();
    assert_eq!(bytes.len() % 2, 0, "even-length hex fixtures");
    (0..bytes.len() / 2)
        .map(|index| {
            u8::from_str_radix(&hex[index * 2..index * 2 + 2], 16).expect("hex fixture nibble")
        })
        .collect()
}

// --- The stub transport (socket-free; the deployment implements the real one) -------

struct StubTransport {
    /// The per-serial raw responses (hex-encoded fixtures).
    responses: BTreeMap<String, Vec<u8>>,
    /// The fallback outcome for serials with no configured response.
    fallback: StubFallback,
}

enum StubFallback {
    Unreachable(String),
}

impl StubTransport {
    fn with_response(serial: &str, hex: &str) -> Self {
        let mut responses = BTreeMap::new();
        responses.insert(serial.to_string(), hex_bytes(hex));
        Self {
            responses,
            fallback: StubFallback::Unreachable(
                "the pinned lab stub serves one serial; everything else is unreachable"
                    .to_string(),
            ),
        }
    }

    fn unreachable(reason: &str) -> Self {
        Self {
            responses: BTreeMap::new(),
            fallback: StubFallback::Unreachable(reason.to_string()),
        }
    }
}

impl OcspTransport for StubTransport {
    fn name(&self) -> &'static str {
        "STUB_OCSP_TRANSPORT_TEST_DOUBLE"
    }

    fn fetch(
        &self,
        _responder: &OcspResponderConfig,
        request: &OcspRequest,
    ) -> Result<Vec<u8>, OcspTransportError> {
        let serial_hex: String = request
            .serial_der_content
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect();
        match self.responses.get(&serial_hex) {
            Some(raw) => Ok(raw.clone()),
            None => match &self.fallback {
                StubFallback::Unreachable(reason) => {
                    Err(OcspTransportError::Unreachable { reason: reason.clone() })
                }
            },
        }
    }
}

fn responder_config() -> OcspResponderConfig {
    OcspResponderConfig::new(
        "https://ocsp.example.invalid/ (a configuration REFERENCE — this program performs \
         no network I/O)"
            .to_string(),
        hex_bytes(RESPONDER_CERT_A_HEX),
    )
    .expect("valid responder config")
}

/// The fixture gate record with ALL FIVE conditions recorded MET.
fn met_gates() -> PncGateConditions {
    let references = [
        "pki-operator-ref",
        "anchor-distribution-ref",
        "ocsp-service-contract-ref",
        "oca-text-verification-pass-ref",
        "d5-closure-ref",
    ];
    let mut gates = PncGateConditions::unmet();
    for (index, condition) in PncGateCondition::ALL.into_iter().enumerate() {
        gates
            .record_met(condition, references[index].to_string())
            .expect("recorded");
    }
    gates
}

