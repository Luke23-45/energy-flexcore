// P1.13 — PostgresIdGenerator: the ID-generation port over uuidv7().
//
// RECORDED DECISION (D-S1 consistency): the P1.12 design generates every
// primary key with PostgreSQL 18's built-in `uuidv7()`. Application-side
// identifiers (the P1.07 `IdGenerator` port feeds domain/entity IDs before
// insert) share the same version policy by querying `SELECT uuidv7()` from
// the same database, so there is exactly one UUID version policy per
// deployment and identifier ordering characteristics match the storage
// defaults (P1.07: "the store's identifiers should match the generator's
// version policy").
//
// Failure policy: ID generation is fail-fast. The port is infallible and
// must never return nil or repeat an identifier; if the database is
// unreachable the call panics with a clear message (a storage outage is an
// operational failure, not user input). Deployments that prefer a
// non-database generator implement the port elsewhere.

use flexcore_contracts::ids::FlexUuid;
use flexcore_ports::id_generator::IdGenerator;
use sqlx::PgPool;
use std::sync::Arc;
use tokio::runtime::Runtime;

/// The ID generator backed by the same PostgreSQL 18 server the store uses.
#[derive(Clone)]
pub struct PostgresIdGenerator {
    pool: PgPool,
    runtime: Arc<Runtime>,
}

impl PostgresIdGenerator {
    /// Builds a generator over the given pool and runtime (both shared
    /// with the owning [`crate::FlexCoreStore`]).
    pub(crate) fn new(pool: PgPool, runtime: Arc<Runtime>) -> Self {
        Self { pool, runtime }
    }
}

impl IdGenerator for PostgresIdGenerator {
    /// A fresh UUIDv7 identifier generated by the database (`uuidv7()`,
    /// PostgreSQL 18 — D-S1). Time-ordered, unique, never nil.
    fn new_uuid(&self) -> FlexUuid {
        let text: String = self
            .runtime
            .block_on(async { sqlx::query_scalar::<_, String>("SELECT uuidv7()::text").fetch_one(&self.pool).await })
            .expect("uuidv7() generation requires a reachable database; FlexCore ID generation is fail-fast (D-S1)");
        FlexUuid::parse(&text)
            .expect("uuidv7() always returns a canonical UUID text value")
    }
}

