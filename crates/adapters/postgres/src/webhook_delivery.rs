/// The named conflict code: a booking under an existing idempotency key
/// with CONFLICTING content (same key, different payload/endpoint). The
/// control-plane port maps this code to its
/// `WebhookDeliveryError::ConflictingDeliveryKey`.
pub const KEY_CONFLICT_CODE: &str = "E_WEBHOOK_KEY_CONFLICT";

/// The service subject this store's per-tenant units of work carry (the
/// audit-correlation identity of the background bookkeeping path — a
/// service identity, never an operator's; constructed through the single
/// greppable claims path, P0.16 rule 5).
const SERVICE_SUBJECT: &str = "postgres-adapter:webhook-delivery-store";

/// The cross-tenant scan/depth walker's service subject (mirrors the
/// P11.20 stuck scanner's `control-plane:stuck-scanner` shape).
const SCAN_SUBJECT: &str = "postgres-adapter:webhook-delivery-scan";

/// The delivery row the store inserts (or, for the collapse read, returns
/// stored). The tenant travels in the caller's [`TenantContext`], never in
/// a loose string field.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WebhookDeliveryInsert {
    /// The delivery row id — canonical UUID text (the 0020 uuid column).
    pub delivery_id: String,
    /// The delivery IDEMPOTENCY KEY (unique per tenant).
    pub delivery_key: String,
    /// The target endpoint id — canonical UUID text.
    pub endpoint_id: String,
    /// The event subject the payload carries.
    pub event_subject: String,
    /// The RAW request body exactly as transmitted.
    pub raw_body: String,
    /// The delivery status (the closed 0020 CHECK vocabulary).
    pub status: String,
    /// The next attempt sequence (1-based; the CHECK requires >= 1).
    pub next_attempt_seq: i64,
    /// Unix millis of the earliest next attempt; `None` = due immediately.
    pub next_attempt_not_before_unix_millis: Option<i64>,
    /// The most recent HTTP response status code, when one was received.
    pub last_response_code: Option<i32>,
}

/// One stored delivery row (the readback shape; the tenant is the unit of
