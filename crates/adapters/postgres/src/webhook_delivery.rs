// P13.09 — PostgreSQL storage half of the outbound webhook-delivery
//         bookkeeping contract (migration 0020: webhook_endpoints,
//         webhook_deliveries, webhook_delivery_attempts,
//         webhook_dead_letters). FRV1-R8-005 (final review): this module
//         lands the recorded composition step of the P13.09 decision
//         record §5 step 1.
//
// The PORT (`WebhookDeliveryStore`) stays single-homed in
// `apps/control-plane/src/webhook_service.rs` (its error vocabulary names
// the app's signing error, so the trait cannot live here); THIS module is
// the storage half the control-plane crate implements the port over — the
// recorded shape (record 21 §5: "`crates/adapters/postgres/src/
// webhook_delivery.rs` implementing the port on `FlexCoreStore`").
//
// Pattern: the recorded edge-enrollment pattern (P6.06) — a standalone
// store that opens ITS OWN tenant-scoped unit of work per call, OUTSIDE
// the per-request UoW bundle (delivery bookkeeping is background-store
// state, not request-transaction state). Every write commits; every
// read-only unit is dropped without commit (the P1.10 adapter contract:
// drop rolls an empty transaction back harmlessly).
//
// TENANT SCOPING IS ABSOLUTE (migration 0020 ENABLE + FORCE RLS): every
// statement runs inside a unit of work whose `flexcore.tenant_id` GUC is
// set from the operation's tenant context — a delivery-scoped operation
// from the operation's OWN tenant (passed by the caller; the dispatcher
// always has the delivery's tenant), and the two cross-tenant operations
// (`list_due_deliveries`, `count_dead_letters`) walk the registered
// tenants ONE PER UNIT OF WORK (the P11.20 stuck-scan `tenant_ids`
// pattern) and merge. No statement of this module ever runs without a
// tenant scope; with RLS a foreign-tenant id reads as absent (P0.16
// rule 5).
//
// IDENTIFIERS: the delivery/endpoint ids arrive as canonical UUID text
// and are bound with `::uuid` (the 0020 columns are uuid; a non-UUID
// caller value is REJECTED here with a named code — the market-store
// `validate_uuid_field` discipline). The attempt and dead-letter ROW ids
// are generated by this module's INSERTs as D-S1 `uuidv7()` (application-
// side generation through the same database server — the 0020
// `gen_random_uuid()` column defaults are the recorded fallback-only
// path, reconciled for the final review as FRV1-R5-008); the port
// records' `attempt_id`/`dead_letter_id` strings are the caller's
// bookkeeping handles (the in-memory fake's keys), never stored here.
// Attempt outcomes are keyed by the UNIQUE `(delivery_id, attempt_seq)`
// constraint, and the one-dead-letter-per-delivery rule by the UNIQUE
// `(delivery_id)` constraint.
//
// The idempotency-key collapse (`webhook_deliveries_key_unique`, UNIQUE
// per tenant) is enforced HERE: an insert under an existing key reads
// the existing row and either returns it (same content) or reports the
// named conflict code — the same-key-different-content rule of the
// service layer, with the database constraint as the backstop.

