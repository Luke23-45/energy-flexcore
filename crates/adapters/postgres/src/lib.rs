#[cfg(test)]
mod tests {
    // The adapter implements the ports; object safety is part of the
    // contract (the composition root holds ports as trait objects). This
    // test compiles trait-object references for every port implemented
    // here, and pins that PgUnitOfWork carries the full port bundle.
    #[test]
    fn every_implemented_port_is_object_safe() {
        use crate::unit_of_work::PgUnitOfWork;
        use flexcore_audit::sink::AuditSink;
        use flexcore_ports::event_outbox::EventOutbox;
        use flexcore_ports::repository::{
            AssetRepository, PortfolioRepository, SiteRepository, TenantRepository,
        };
        use flexcore_storage::audit_read::AuditEventReader;

        fn takes_dyn_clock(_: &dyn flexcore_ports::clock::Clock) {}
        fn takes_dyn_ids(_: &dyn flexcore_ports::id_generator::IdGenerator) {}
        fn takes_dyn_outbox(_: &dyn EventOutbox) {}
        fn takes_dyn_tenants(_: &dyn TenantRepository) {}
        fn takes_dyn_portfolios(_: &dyn PortfolioRepository) {}
        fn takes_dyn_sites(_: &dyn SiteRepository) {}
        fn takes_dyn_assets(_: &dyn AssetRepository) {}
        fn takes_dyn_audit(_: &dyn AuditSink) {}
        // P4.36 — the audit-events reader joins the implemented-port
        // evidence (SELECT-only; see audit_read.rs).
        fn takes_dyn_audit_read(_: &dyn AuditEventReader) {}

        fn assert_full_port_bundle<T>()
        where
            T: TenantRepository
                + PortfolioRepository
                + SiteRepository
                + AssetRepository
                + EventOutbox
                + AuditSink
                + AuditEventReader,
        {
        }
        assert_full_port_bundle::<PgUnitOfWork>;

        let _ = takes_dyn_clock;
        let _ = takes_dyn_ids;
        let _ = takes_dyn_outbox;
        let _ = takes_dyn_tenants;
        let _ = takes_dyn_portfolios;
        let _ = takes_dyn_sites;
        let _ = takes_dyn_assets;
        let _ = takes_dyn_audit;
    }
}
