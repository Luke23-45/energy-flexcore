// P1.13 — PostgreSQL adapter: repositories, migrations, RLS tenant context,
//         transactional outbox, and the append-only audit sink.
//
// Implements the P1.12 schema design (ledger
// `ledger/phase-01-rust-foundation/12_schema_design.md`, decisions D-S1..D-S5
// exactly) and the P1.07/P1.10 port traits exactly as defined:
//
// | Port (single home)                  | Adapter implementation |
// |---|---|
// | `flexcore_ports::repository::{TenantRepository, PortfolioRepository, SiteRepository, AssetRepository}` | [`unit_of_work::PgUnitOfWork`] — every statement runs inside the unit of work's one native transaction |
// | `flexcore_ports::event_outbox::EventOutbox` | `append` on [`unit_of_work::PgUnitOfWork`] (state change + outbox row in ONE transaction); the publisher side (`pending` / `record_attempt` / `mark_delivered` / `mark_failed`) on [`store::FlexCoreStore`] |
// | `flexcore_audit::sink::AuditSink` (append-only) | [`unit_of_work::PgUnitOfWork`] (inside the transaction) and [`store::FlexCoreStore`] (self-scoping autocommit append) |
// | `flexcore_ports::clock::Clock` | [`clock::SystemClock`] |
// | `flexcore_ports::id_generator::IdGenerator` | [`id_generator::PostgresIdGenerator`] — `SELECT uuidv7()`, sharing the D-S1 PK version policy |
// | Telemetry repository (P2.06; no port trait — the P2.11 contract is being implemented concurrently) | [`telemetry`] on [`unit_of_work::PgUnitOfWork`]: insert (single + batch), time-range query, latest-per-asset, quarantine write/list, all tenant-scoped through the same unit-of-work transaction |
// | Versioned corrections + as-of reads (P2.31, foundations §6.4; no port trait — same recorded status) | [`corrections`] on [`unit_of_work::PgUnitOfWork`]: correction insert (new versioned row, original intact), per-identity version listing, as-of range/history reads |
// | `flexcore_storage::schedule_store::ScheduleRecordStore` (P3.21; storage-side contract, recorded home deviation) | [`schedule_store`] on [`unit_of_work::PgUnitOfWork`]: §12.6 schedule-result record insert + tenant-scoped find (migration 0013), inside the caller's transaction so the record and the `ScheduleProposed` outbox row are atomic (§15.5) |
// | `flexcore_storage::command_store::CommandRecordStore` + `flexcore_storage::feasibility_check::FeasibilityCheckStore` (P4.10/P4.30; storage-side contracts, same recorded home deviation) | [`command_store`] / [`feasibility_check`] on [`unit_of_work::PgUnitOfWork`]: command records + the compare-and-swap state transition + immutable journal rows (migration 0016) and the append-only feasibility-check evidence records (migration 0017), all inside the caller's transaction so each state change and its paired outbox rows are atomic (§15.5) |
// | `flexcore_storage::audit_read::AuditEventReader` (P4.36; storage-side contract, same recorded home deviation) | [`audit_read`] on [`unit_of_work::PgUnitOfWork`]: the SELECT-only, tenant-scoped read half of the append-only `audit_records` table (migration 0008) — the §15.2 `/api/v1/audit-events` read resource; NO write statement exists in that module (writes stay on the P1.10 `AuditSink`) |
//
// ## Recorded decisions (full rationale in the crate README)
//
// - **Runtime queries**: `sqlx::query` (runtime-checked), never the
//   compile-time `query!` macros — those need sqlx-data generated by a
//   build against a live database, which this crate does not require.
// - **Sync ports bridged async**: the port traits are sync (P1.07 recorded
//   rule); each [`store::FlexCoreStore`] owns a private Tokio runtime and
//   the sync methods block on it. Callers must invoke the ports from
//   synchronous contexts (e.g. `spawn_blocking` inside an async service).
// - **FlexUuid ↔ PG uuid**: identifiers travel as canonical hyphenated
//   text, bound as text parameters and cast with `::uuid` in SQL (and
//   selected back with `::text`). The sqlx `uuid` feature is not enabled in
//   the workspace pin, and the text mapping keeps the contracts type as the
//   single representation of record.
// - **Tenant context**: every tenant-scoped unit of work issues
//   `SELECT set_config('flexcore.tenant_id', $1, true)` — transaction-scoped
//   (SET LOCAL semantics), read by the P1.12 §5.1 RLS policies. An
//   unset/empty setting fails closed (zero rows, no writes).
// - **Drop = rollback**: an unfinalized [`unit_of_work::PgUnitOfWork`]
//   spawns a rollback of its native transaction on drop (P1.10 adapter
//   contract rule 4).
//
// ## Scope and control status
//
// Persistence for the design baseline only. The entire 0.x line is
// simulation-only (AGENTS.md §3 rule 5): this adapter grants no control
// authority, performs no device writes, and carries no protection-grade
// functionality. No telemetry tables exist in this schema (Phase 2 owns
// them, P1.12 §2.1).

