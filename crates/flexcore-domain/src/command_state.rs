// P0.11 — Command state machine: states, transitions, invariants (Phase 0 freeze)
//
// Implements `ledger/phase-00-product-freeze/11_command_state_machine.md`.
// Normative source: report §14.1–§14.5; foundations specification governs on
// conflict. This module is the code form of the frozen transition table,
// which is the test oracle for the command state machine in later phases:
// exactly the transitions in the frozen table, no more, no fewer.
//
// Frozen rules encoded here:
//
// - **14 states:** the 8 forward states PROPOSED, VALIDATED, FEASIBLE,
//   APPROVED, ISSUED, ACKNOWLEDGED, TRACKING, COMPLETED; and REJECTED,
//   FAILED, EXPIRED, CANCELLED, SUPERSEDED, FALLBACK.
// - **27 state-to-state transitions**, reproduced verbatim from the freeze
//   table. No shortcut edges exist: there is no PROPOSED → ISSUED, no
//   PROPOSED → FEASIBLE, no VALIDATED → APPROVED. Each of the three gates is
//   its own state transition.
// - **Terminal states** (as drawn in the freeze): COMPLETED, REJECTED,
//   CANCELLED, SUPERSEDED, FALLBACK. FAILED and EXPIRED are **not** terminal
//   — their only outgoing edge is to FALLBACK (transitions 26–27).
// - **Three-gate distinction:** validation (→ VALIDATED: schema, freshness,
//   asset capability, ramp, SoC, and command-policy checks), feasibility
//   (→ FEASIBLE: relevant network model check within declared scope and
//   tolerances), and authorization (→ APPROVED: required human/policy
//   authorization) are **distinct gates**. Network feasibility is **not**
//   operator authorization and cannot be derived from a passing power-flow
//   run. Every transition has explicit preconditions, timeout, and audit
//   event; failure does not silently skip the next gate.
// - **Acknowledgement is not physical delivery:** ACKNOWLEDGED confirms
//   receipt/acceptance at the application layer only. ISSUED, ACKNOWLEDGED,
//   and TRACKING measure progressively more evidence; none is COMPLETED
//   until the defined delivery criterion is satisfied.
// - **SUPERSEDED is not CANCELLED:** CANCELLED is an explicit operator/policy
//   cancellation (the cause is the cancellation act); SUPERSEDED is
//   invalidation by a newer approved schedule/command revision (the cause is
//   the replacement), retained for audit. They are separate states and must
//   never be merged.
// - **Three rejection points:** PROPOSED → REJECTED (malformed/unsupported),
//   VALIDATED → REJECTED (capability/network failure), FEASIBLE → REJECTED
//   (authorization denied).
// - **Fleet semantics:** partial fleet success is represented per asset; a
//   portfolio-level acknowledgement is never inferred from the first
//   responding device. Each asset's command follows its own lifecycle.
//
// Scope: the command lifecycle is a protected platform invariant owned by the
// platform kernel (report §0.2, §5.7); plugins may propose and request
// validation but can never authorize, issue, or select the control-authority
// mode. The entire 0.x line is simulation-only; nothing here authorises field
// control or device writes.

/// The 14 states of the protected command lifecycle (report §14.1, §14.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum CommandState {
    /// `PROPOSED` — candidate setpoint/schedule generated by an optimizer,
    /// policy, adapter, or operator.
    Proposed,
    /// `VALIDATED` — schema, freshness, asset capability, ramp, SoC, and
    /// command policy checks pass (validation gate).
    Validated,
    /// `FEASIBLE` — relevant network model check passes within declared model
    /// scope and tolerances (feasibility gate).
    Feasible,
    /// `APPROVED` — required human/policy authorization granted
    /// (authorization gate).
    Approved,
    /// `ISSUED` — signed command was sent to the selected gateway/adapter.
    Issued,
    /// `ACKNOWLEDGED` — gateway/device accepted the command at the
    /// application layer (not physical delivery).
    Acknowledged,
    /// `TRACKING` — measured response is compared with requested behaviour.
    Tracking,
    /// `COMPLETED` — defined delivery criterion satisfied (terminal).
    Completed,
    /// `REJECTED` — candidate rejected before issue (terminal).
    Rejected,
    /// `FAILED` — execution/communication/tracking failed (not terminal;
    /// exits only via `FALLBACK`).
    Failed,
    /// `EXPIRED` — validity window ended before execution, application-level
    /// acceptance, or completion (not terminal; exits only via `FALLBACK`).
    Expired,
    /// `CANCELLED` — explicitly cancelled by an operator or policy before
    /// issue or while supported (terminal; distinct from `SUPERSEDED`).
    Cancelled,
    /// `SUPERSEDED` — invalidated by a newer approved schedule/command
    /// revision before completion; retained for audit and explicitly distinct
    /// from explicit cancellation (terminal).
    Superseded,
    /// `FALLBACK` — resource/site-specific fallback policy activated
    /// (terminal).
    Fallback,
}

impl CommandState {
    /// All 14 states.
    pub const ALL: [CommandState; 14] = [
        CommandState::Proposed,
        CommandState::Validated,
        CommandState::Feasible,
        CommandState::Approved,
        CommandState::Issued,
        CommandState::Acknowledged,
        CommandState::Tracking,
        CommandState::Completed,
        CommandState::Rejected,
        CommandState::Failed,
        CommandState::Expired,
        CommandState::Cancelled,
        CommandState::Superseded,
        CommandState::Fallback,
    ];

    /// The canonical SCREAMING_SNAKE name from the frozen lifecycle.
    pub const fn name(self) -> &'static str {
        match self {
            CommandState::Proposed => "PROPOSED",
            CommandState::Validated => "VALIDATED",
            CommandState::Feasible => "FEASIBLE",
            CommandState::Approved => "APPROVED",
            CommandState::Issued => "ISSUED",
            CommandState::Acknowledged => "ACKNOWLEDGED",
            CommandState::Tracking => "TRACKING",
            CommandState::Completed => "COMPLETED",
            CommandState::Rejected => "REJECTED",
            CommandState::Failed => "FAILED",
            CommandState::Expired => "EXPIRED",
            CommandState::Cancelled => "CANCELLED",
            CommandState::Superseded => "SUPERSEDED",
            CommandState::Fallback => "FALLBACK",
        }
    }
}

/// Whether the state is terminal in the frozen table.
///
/// Terminal per the freeze: `COMPLETED`, `REJECTED`, `CANCELLED`,
/// `SUPERSEDED`, `FALLBACK`. `FAILED` and `EXPIRED` are **not** terminal —
/// their only outgoing edge is to `FALLBACK` (frozen transitions 26–27), so
/// they can still leave their state.
pub fn is_terminal(state: CommandState) -> bool {
    matches!(
        state,
        CommandState::Completed
            | CommandState::Rejected
            | CommandState::Cancelled
            | CommandState::Superseded
            | CommandState::Fallback
    )
}

/// The error returned when a transition is not in the frozen table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TransitionError {
    /// The requested transition does not appear in the frozen §14.1 table.
    /// No transition outside the table is permitted, including
    /// self-transitions and gate-skipping shortcuts.
    NotPermitted {
        /// The state the transition was requested from.
        from: CommandState,
        /// The state the transition was requested to.
        to: CommandState,
    },
}

impl std::fmt::Display for TransitionError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            TransitionError::NotPermitted { from, to } => write!(
                f,
                "transition {} -> {} is not in the frozen command state machine",
                from.name(),
                to.name()
            ),
        }
    }
}

impl std::error::Error for TransitionError {}

/// Attempts a transition `from -> to` against the frozen §14.1 table.
///
/// Every one of the 27 frozen edges is allowed; **no** edge outside the table
/// is allowed — not gate-skipping shortcuts (e.g. `PROPOSED → ISSUED`), not
/// transitions out of terminal states, not self-transitions, and not exits
/// from `FAILED`/`EXPIRED` other than `FALLBACK`. On success the destination
/// state is returned unchanged.
pub fn try_transition(
    from: CommandState,
    to: CommandState,
) -> Result<CommandState, TransitionError> {
    let permitted = match from {
        CommandState::Proposed => matches!(to, CommandState::Validated | CommandState::Rejected),
        CommandState::Validated => {
            matches!(
                to,
                CommandState::Feasible | CommandState::Rejected | CommandState::Superseded
            )
        }
        CommandState::Feasible => {
            matches!(
                to,
                CommandState::Approved | CommandState::Rejected | CommandState::Superseded
            )
        }
        CommandState::Approved => {
            matches!(
                to,
                CommandState::Issued
                    | CommandState::Expired
                    | CommandState::Superseded
                    | CommandState::Cancelled
            )
        }
        CommandState::Issued => {
            matches!(
                to,
                CommandState::Acknowledged
                    | CommandState::Failed
                    | CommandState::Expired
                    | CommandState::Superseded
                    | CommandState::Cancelled
            )
        }
        CommandState::Acknowledged => {
            matches!(
                to,
                CommandState::Tracking
                    | CommandState::Failed
                    | CommandState::Expired
                    | CommandState::Superseded
            )
        }
        CommandState::Tracking => {
            matches!(
                to,
                CommandState::Completed
                    | CommandState::Failed
                    | CommandState::Expired
                    | CommandState::Superseded
            )
        }
        // Frozen transitions 26–27: FAILED and EXPIRED exit only via FALLBACK.
        CommandState::Failed => matches!(to, CommandState::Fallback),
        CommandState::Expired => matches!(to, CommandState::Fallback),
        // COMPLETED, REJECTED, CANCELLED, SUPERSEDED, FALLBACK are terminal:
        // no outgoing edges in the frozen table.
        CommandState::Completed
        | CommandState::Rejected
        | CommandState::Cancelled
        | CommandState::Superseded
        | CommandState::Fallback => false,
    };

    if permitted {
        Ok(to)
    } else {
        Err(TransitionError::NotPermitted { from, to })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use CommandState::*;

    /// The frozen §14.1 transition table, transcribed verbatim from
    /// `11_command_state_machine.md` §2 (27 state-to-state edges, in table
    /// order). Kept literally so the frozen table and the implementation can
    /// be diffed mechanically. `pub(super)` so the P1.06 property-test
    /// module below can derive its oracle from this one copy of the table.
    pub(super) const FROZEN_EDGES: [(CommandState, CommandState); 27] = [
        (Proposed, Validated),        // 1  — schema, freshness, asset checks pass
        (Proposed, Rejected),         // 2  — malformed / unsupported
        (Validated, Feasible),        // 3  — network checks pass
        (Validated, Rejected),        // 4  — capability / network failure
        (Validated, Superseded),      // 5  — newer approved revision replaces it
        (Feasible, Approved),         // 6  — policy / operator authorization
        (Feasible, Rejected),         // 7  — authorization denied
        (Feasible, Superseded),       // 8  — newer approved revision replaces it
        (Approved, Issued),           // 9  — signed, sequenced command sent
        (Approved, Expired),          // 10 — validity ends before issue
        (Approved, Superseded),       // 11 — newer approved revision replaces it
        (Approved, Cancelled),        // 12 — operator/policy cancellation
        (Issued, Acknowledged),       // 13 — device/gateway accepts
        (Issued, Failed),             // 14 — NACK / timeout / transport failure
        (Issued, Expired),            // 15 — validity ends before acknowledgement
        (Issued, Superseded),         // 16 — newer approved revision replaces it
        (Issued, Cancelled),          // 17 — supported cancellation semantics
        (Acknowledged, Tracking),     // 18 — telemetry observed
        (Acknowledged, Failed),       // 19 — no expected response
        (Acknowledged, Expired),      // 20 — validity ends before tracking completes
        (Acknowledged, Superseded),   // 21 — newer approved revision replaces it
        (Tracking, Completed),        // 22 — acceptance criterion satisfied
        (Tracking, Failed),           // 23 — tracking deviation / timeout
        (Tracking, Expired),          // 24 — validity ends
        (Tracking, Superseded),       // 25 — newer approved revision replaces it
        (Failed, Fallback),           // 26 — asset/site policy activated
        (Expired, Fallback),          // 27 — policy requires
    ];

    #[test]
    fn exactly_14_states() {
        assert_eq!(CommandState::ALL.len(), 14);
    }

    #[test]
    fn state_names_match_frozen_vocabulary() {
        let names: [&str; 14] = [
            Proposed.name(),
            Validated.name(),
            Feasible.name(),
            Approved.name(),
            Issued.name(),
            Acknowledged.name(),
            Tracking.name(),
            Completed.name(),
            Rejected.name(),
            Failed.name(),
            Expired.name(),
            Cancelled.name(),
            Superseded.name(),
            Fallback.name(),
        ];
        assert_eq!(
            names,
            [
                "PROPOSED",
                "VALIDATED",
                "FEASIBLE",
                "APPROVED",
                "ISSUED",
                "ACKNOWLEDGED",
                "TRACKING",
                "COMPLETED",
                "REJECTED",
                "FAILED",
                "EXPIRED",
                "CANCELLED",
                "SUPERSEDED",
                "FALLBACK"
            ]
        );
    }

    #[test]
    fn every_frozen_edge_is_allowed() {
        for (i, &(from, to)) in FROZEN_EDGES.iter().enumerate() {
            assert_eq!(
                try_transition(from, to),
                Ok(to),
                "frozen edge #{} ({:?} -> {:?}) must be allowed",
                i + 1,
                from,
                to
            );
        }
    }

    #[test]
    fn terminal_states_are_exactly_the_five_frozen_ones() {
        assert!(is_terminal(Completed));
        assert!(is_terminal(Rejected));
        assert!(is_terminal(Cancelled));
        assert!(is_terminal(Superseded));
        assert!(is_terminal(Fallback));
        // FAILED and EXPIRED are NOT terminal: they can still go to FALLBACK.
        assert!(!is_terminal(Proposed));
        assert!(!is_terminal(Validated));
        assert!(!is_terminal(Feasible));
        assert!(!is_terminal(Approved));
        assert!(!is_terminal(Issued));
        assert!(!is_terminal(Acknowledged));
        assert!(!is_terminal(Tracking));
        assert!(!is_terminal(Failed));
        assert!(!is_terminal(Expired));
    }

    #[test]
    fn failed_and_expired_exit_only_via_fallback() {
        for &from in &[Failed, Expired] {
            for &to in CommandState::ALL.iter() {
                let result = try_transition(from, to);
                if to == Fallback {
                    assert_eq!(result, Ok(Fallback));
                } else {
                    assert_eq!(
                        result,
                        Err(TransitionError::NotPermitted { from, to }),
                        "FAILED/EXPIRED may only transition to FALLBACK"
                    );
                }
            }
        }
    }

    #[test]
    fn gate_skipping_shortcuts_are_rejected() {
        let forbidden = [
            (Proposed, Issued),
            (Proposed, Approved),
            (Proposed, Feasible),
            (Proposed, Acknowledged),
            (Proposed, Tracking),
            (Proposed, Completed),
            (Validated, Approved),
            (Validated, Issued),
            (Validated, Completed),
            (Feasible, Issued),
            (Feasible, Acknowledged),
            (Feasible, Tracking),
            (Feasible, Completed),
            (Approved, Acknowledged),
            (Approved, Tracking),
            (Approved, Completed),
            (Issued, Completed),
            (Issued, Tracking),
            (Acknowledged, Completed),
            (Tracking, Issued),
            (Tracking, Acknowledged),
            (Tracking, Approved),
        ];
        for &(from, to) in forbidden.iter() {
            assert_eq!(
                try_transition(from, to),
                Err(TransitionError::NotPermitted { from, to }),
                "shortcut {:?} -> {:?} must be rejected",
                from,
                to
            );
        }
    }

    #[test]
    fn transitions_out_of_terminal_states_are_rejected() {
        let terminal = [Completed, Rejected, Cancelled, Superseded, Fallback];
        for &from in terminal.iter() {
            for &to in CommandState::ALL.iter() {
                assert_eq!(
                    try_transition(from, to),
                    Err(TransitionError::NotPermitted { from, to }),
                    "terminal state {:?} must have no outgoing edges (to {:?})",
                    from,
                    to
                );
            }
        }
    }

    #[test]
    fn no_self_transition_for_any_state() {
        for &state in CommandState::ALL.iter() {
            assert_eq!(
                try_transition(state, state),
                Err(TransitionError::NotPermitted { from: state, to: state }),
                "no self-transition exists for {:?}",
                state
            );
        }
    }

    #[test]
    fn backwards_transitions_are_rejected() {
        let forbidden = [
            (Validated, Proposed),
            (Feasible, Validated),
            (Approved, Feasible),
            (Issued, Approved),
            (Acknowledged, Issued),
            (Tracking, Acknowledged),
            (Completed, Tracking),
            (Rejected, Proposed),
            (Cancelled, Approved),
            (Superseded, Tracking),
            (Fallback, Failed),
        ];
        for &(from, to) in forbidden.iter() {
            assert_eq!(
                try_transition(from, to),
                Err(TransitionError::NotPermitted { from, to }),
                "backwards transition {:?} -> {:?} must be rejected",
                from,
                to
            );
        }
    }

    #[test]
    fn cancelled_is_reachable_only_from_approved_and_issued() {
        // Frozen property (§2.2): CANCELLED is reachable only from APPROVED
        // and ISSUED.
        for &from in CommandState::ALL.iter() {
            let result = try_transition(from, Cancelled);
            if from == Approved || from == Issued {
                assert_eq!(result, Ok(Cancelled));
            } else {
                assert_eq!(result, Err(TransitionError::NotPermitted { from, to: Cancelled }));
            }
        }
    }

    #[test]
    fn superseded_is_reachable_from_exactly_six_states() {
        // Frozen property (§2.2): SUPERSEDED is reachable from VALIDATED,
        // FEASIBLE, APPROVED, ISSUED, ACKNOWLEDGED, and TRACKING.
        let expected = [Validated, Feasible, Approved, Issued, Acknowledged, Tracking];
        for &from in CommandState::ALL.iter() {
            let result = try_transition(from, Superseded);
            if expected.contains(&from) {
                assert_eq!(result, Ok(Superseded));
            } else {
                assert_eq!(result, Err(TransitionError::NotPermitted { from, to: Superseded }));
            }
        }
    }

    #[test]
    fn expired_is_reachable_from_exactly_four_states() {
        // Frozen property (§2.2): EXPIRED is reachable from APPROVED, ISSUED,
        // ACKNOWLEDGED, and TRACKING.
        let expected = [Approved, Issued, Acknowledged, Tracking];
        for &from in CommandState::ALL.iter() {
            let result = try_transition(from, Expired);
            if expected.contains(&from) {
                assert_eq!(result, Ok(Expired));
            } else {
                assert_eq!(result, Err(TransitionError::NotPermitted { from, to: Expired }));
            }
        }
    }

    #[test]
    fn rejected_is_reachable_from_exactly_three_gates() {
        // Frozen property (§2.2): three rejection points — PROPOSED,
        // VALIDATED, FEASIBLE.
        let expected = [Proposed, Validated, Feasible];
        for &from in CommandState::ALL.iter() {
            let result = try_transition(from, Rejected);
            if expected.contains(&from) {
                assert_eq!(result, Ok(Rejected));
            } else {
                assert_eq!(result, Err(TransitionError::NotPermitted { from, to: Rejected }));
            }
        }
    }

    #[test]
    fn happy_path_forward_walk() {
        let path = [
            (Proposed, Validated),
            (Validated, Feasible),
            (Feasible, Approved),
            (Approved, Issued),
            (Issued, Acknowledged),
            (Acknowledged, Tracking),
            (Tracking, Completed),
        ];
        for &(from, to) in path.iter() {
            assert_eq!(try_transition(from, to), Ok(to));
        }
    }
}

// P1.06 — property tests over generated command/state sequences (ledger P1.06
//         step 6: "property test over generated command sequences preserving
//         the state machine").
//
// Generator: the in-crate splitmix64 (`crate::test_rng`) with fixed seeds —
// no external property-test dependency is permitted (dependency rule,
// `tools/check_dependency_rule.py`); see the module documentation there for
// the recorded choice. All runs are deterministic.
#[cfg(test)]
mod property_tests {
    use super::{CommandState, is_terminal, try_transition};
    use crate::test_rng::SplitMix64;

    /// Property: over generated (from, to) pairs across all 14 states, the
    /// transition function accepts **exactly** the frozen-table edges — no
    /// edge outside the table ever succeeds, and terminal states never emit
    /// a transition at all.
    #[test]
    fn property_random_pairs_accept_exactly_the_frozen_edges() {
        let mut rng = SplitMix64::new(0x5EED_5EED_5EED_5EED);
        for _ in 0..4096 {
            let from = *rng.pick(&CommandState::ALL);
            let to = *rng.pick(&CommandState::ALL);
            let in_table = super::tests::FROZEN_EDGES
                .iter()
                .any(|&(f, t)| f == from && t == to);
            let result = try_transition(from, to);
            assert_eq!(
                result.is_ok(),
                in_table,
                "{} -> {} must {}the frozen table",
                from.name(),
                to.name(),
                if in_table { "be in " } else { "be outside " }
            );
            if is_terminal(from) {
                assert!(
                    result.is_err(),
                    "terminal state {} must never emit a transition",
                    from.name()
                );
            }
        }
    }

    /// Property: over generated command sequences — random legal walks that
    /// start at PROPOSED and repeatedly take a randomly chosen frozen
    /// successor — every step succeeds, never leaves the frozen table, and
    /// every walk terminates in one of the five terminal states.
    #[test]
    fn property_random_walks_follow_frozen_edges_and_terminate() {
        for seed in [1u64, 0xDEAD_BEEF, 0x1234_5678_9ABC_DEF0] {
            let mut rng = SplitMix64::new(seed);
            for _ in 0..256 {
                let mut current = CommandState::Proposed;
                for _step in 0..24 {
                    let successors: Vec<CommandState> = super::tests::FROZEN_EDGES
                        .iter()
                        .filter(|&&(f, _)| f == current)
                        .map(|&(_, t)| t)
                        .collect();
                    if successors.is_empty() {
                        break; // terminal: no outgoing edge exists
                    }
                    let next = *rng.pick(&successors);
                    assert_eq!(
                        try_transition(current, next),
                        Ok(next),
                        "walk step {} -> {} must follow the frozen table",
                        current.name(),
                        next.name()
                    );
                    current = next;
                }
                assert!(
                    is_terminal(current),
                    "walk must end in a terminal state, ended in {}",
                    current.name()
                );
            }
        }
    }
}
